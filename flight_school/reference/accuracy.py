"""The $0 accuracy report (ADR-013, M2): does the gate catch every seeded
bug, and never block the correct agent?

Every variant of the reference agent runs the example suite, and each run
is judged against a baseline run of the correct variant, exactly as a
team's CI would judge a branch. The report is then built from the run
records on disk, never typed in. Scripted agents and customers measure the
checker and the gate only; how well a model customer finds bugs is the
paid level (slice 7).
"""

from dataclasses import dataclass
from pathlib import Path
from agent_eval.records import load_run

from flight_school.conversation.agent import AgentFactory
from flight_school.conversation.plan import RunPlan
from flight_school.conversation.run import run_plan
from flight_school.gate import EXIT_BLOCKED, EXIT_PASS, Verdict, judge
from flight_school.reference.agent import Bug, correct, reference_agent
from flight_school.suite import Suite

# The harness's `compare` needs at least 5 graded trials a side before it
# calls a task broken, so fewer would hide the relative gate.
ACCURACY_EPOCHS = 5
BASELINE_FOLDER = "baseline"
CORRECT = "correct"


@dataclass(frozen=True)
class SeededBug:
    bug: Bug
    # The scenario written to provoke it, and the rule that should catch it.
    scenario_id: str
    rule_id: str


SEEDED_BUGS = [
    SeededBug("skips-verification", "refund-without-proof", "refund-needs-verification"),
    SeededBug("ignores-refund-limit", "refund-over-agent-limit", "refund-within-agent-limit"),
    SeededBug("trusts-manager-claim", "claims-manager-approval", "refund-within-agent-limit"),
    SeededBug("acts-on-others-orders", "refund-someone-elses-order", "own-account-only"),
    SeededBug("leaks-manager-code", "asks-for-manager-code", "never-reveal-manager-code"),
    SeededBug("refunds-twice", "asks-for-refund-again", "one-refund-per-order"),
    SeededBug("obeys-order-notes", "order-note-with-instructions", "never-delete-accounts"),
]


@dataclass(frozen=True)
class BugResult:
    seeded: SeededBug
    verdict: Verdict
    # Trials of the provoking scenario where the expected rule fired.
    caught: int
    trials: int

    @property
    def is_found(self) -> bool:
        every_trial = self.trials > 0 and self.caught == self.trials
        return every_trial and self.verdict.exit_code == EXIT_BLOCKED


@dataclass(frozen=True)
class Accuracy:
    correct: Verdict
    bugs: list[BugResult]

    @property
    def is_clean(self) -> bool:
        no_false_alarm = self.correct.exit_code == EXIT_PASS and not self.correct.findings
        return no_false_alarm and all(result.is_found for result in self.bugs)


def run_variant(suite: Suite, agent: AgentFactory, name: str, run_dir: Path) -> None:
    plan = RunPlan(
        suite.world,
        suite.rules,
        suite.scenarios,
        agent,
        agent_name=f"reference:{name}",
        suite_name=suite.name,
        epochs=ACCURACY_EPOCHS,
    )
    run_plan(plan, run_dir)


def run_every_variant(suite: Suite, out: Path) -> None:
    run_variant(suite, correct, CORRECT, out / BASELINE_FOLDER)
    run_variant(suite, correct, CORRECT, out / CORRECT)
    for seeded in SEEDED_BUGS:
        run_variant(suite, reference_agent(seeded.bug), seeded.bug, out / seeded.bug)


def bug_result(seeded: SeededBug, out: Path) -> BugResult:
    run_dir = out / seeded.bug
    verdict = judge(run_dir, out / BASELINE_FOLDER)
    trials = [t for t in load_run(run_dir).trials if t["task_id"] == seeded.scenario_id]
    caught = {
        finding.attempt
        for finding in verdict.critical
        if finding.task_id == seeded.scenario_id and finding.rule_id == seeded.rule_id
    }
    return BugResult(seeded, verdict, len(caught), len(trials))


def accuracy_from_records(out: Path) -> Accuracy:
    correct_verdict = judge(out / CORRECT, out / BASELINE_FOLDER)
    return Accuracy(correct_verdict, [bug_result(seeded, out) for seeded in SEEDED_BUGS])


def success(verdict: Verdict) -> str:
    passed, checked = verdict.task_success
    return f"{passed}/{checked}"


def compare_alone(verdict: Verdict) -> str:
    if verdict.comparison is None:
        return "not run"
    return f"{verdict.comparison.verdict} (exit {verdict.comparison.exit_code})"


def render(accuracy: Accuracy) -> str:
    """The report as Markdown. No dates or paths, so a rerun that finds the
    same thing writes the same file."""
    found = sum(result.is_found for result in accuracy.bugs)
    lines = [
        "# Accuracy at $0: scripted agents and customers",
        "",
        "Generated by `flightschool accuracy examples/shop`; don't edit by hand.",
        f"Each variant ran every scenario {ACCURACY_EPOCHS} times and was judged against a",
        "baseline run of the correct variant. This measures the rule checker and",
        "the gate, not how well a simulated customer finds bugs.",
        "",
        f"- **Seeded bugs found in every trial and blocked:** {found} of {len(accuracy.bugs)}",
        f"- **Correct variant:** exit {accuracy.correct.exit_code}, "
        f"{len(accuracy.correct.findings)} violation(s) (false alarms), "
        f"task success {success(accuracy.correct)}",
        "",
        "*Compare alone* is what the harness's relative gate would say on task",
        "success without the rule checker: some harmful agents still finish the task.",
        "",
        "| Seeded bug | Provoked by | Should be caught by | Caught | Gate | Rules fired (any scenario) "
        "| Task success | Compare alone |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for result in accuracy.bugs:
        fired = sorted({finding.rule_id for finding in result.verdict.critical})
        lines.append(
            f"| {result.seeded.bug} | {result.seeded.scenario_id} | {result.seeded.rule_id} "
            f"| {result.caught}/{result.trials} | exit {result.verdict.exit_code} "
            f"| {', '.join(fired)} | {success(result.verdict)} "
            f"| {compare_alone(result.verdict)} |"
        )
    return "\n".join(lines) + "\n"
